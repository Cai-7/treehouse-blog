"""Cut the site's two Chinese fonts into small web-font chunks.

    pip install fonttools brotli        # once
    python3 tools/build_fonts.py        # after adding posts with new characters

Chinese fonts are several MB each, so instead of sending the whole file this script:
  1. collects every character the site uses (posts, lists, page text, scripts),
  2. keeps only those glyphs, ordered by how often each character appears,
  3. cuts them into chunks and writes one @font-face per chunk with a unicode-range.
A browser then downloads only the chunks containing characters on the page it is showing; the
most common characters sit in the first chunk, so a typical page needs just one or two.

Characters added later that are not in any chunk simply fall back to the system font until the
script is run again.

Input:  tools/fonts-src/   the original .ttf/.otf files (see FONTS below)
Output: public/fonts/<slug>/   chunk files and the font's license notice
        src/styles/fonts.css   the @font-face rules
"""
import glob
import hashlib
import re
import shutil
import sys
from collections import Counter
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools/fonts-src"
OUT = ROOT / "public/fonts"
CSS = ROOT / "src/styles/fonts.css"

# family: the name used in CSS. The subsets get their own name, because the original fonts ask
# modified versions not to use the original names.
FONTS = [
    {
        "family": "TH Marker", "slug": "marker", "source": "LXGW Marker Gothic（霞鹜漫黑）",
        "weights": {400: ["LXGWMarkerGothic*.ttf", "LXGWMarkerGothic*.otf", "*MarkerGothic*.ttf"]},
    },
    {
        "family": "TH Hand", "slug": "hand", "source": "Yozai（悠哉字体）",
        # Regular if you have it; otherwise Light stands in as the normal weight.
        "weights": {400: ["Yozai-Regular.ttf", "Yozai*Regular*.ttf", "Yozai-Light.ttf", "Yozai*Light*.ttf"],
                    500: ["Yozai-Medium.ttf", "Yozai*Medium*.ttf"]},
    },
]

# Where the site's text lives.
TEXT_GLOBS = [
    "src/**/*.md", "src/**/*.mdx", "src/**/*.yaml", "src/**/*.yml", "src/**/*.json",
    "src/**/*.astro", "src/scripts/*.js", "tools/render.py", "tools/preview_router.js",
]

# Always included, so punctuation and Latin fallbacks never come from another font mid-sentence.
ALWAYS = "".join(chr(c) for c in range(0x20, 0x7F)) + "，。、；：？！“”‘’（）《》〈〉【】「」『』—…·～￥％＋－×÷"

FIRST_CHUNK = 260   # the most frequent characters: usually all a page needs
CHUNK = 320


def corpus():
    counts = Counter()
    for pattern in TEXT_GLOBS:
        for path in glob.glob(str(ROOT / pattern), recursive=True):
            try:
                text = Path(path).read_text(encoding="utf-8")
            except (UnicodeDecodeError, OSError):
                continue
            counts.update(ch for ch in text if ord(ch) >= 0x20 and not ch.isspace())
    return counts


def find_source(patterns):
    for pattern in patterns:
        hits = sorted(SRC.glob(pattern))
        if hits:
            return hits[0]
    return None


def ranges(codepoints):
    """[0x4e00, 0x4e01, 0x4e03] -> 'U+4E00-4E01, U+4E03'"""
    out = []
    cps = sorted(codepoints)
    start = prev = cps[0]
    for cp in cps[1:] + [None]:
        if cp is not None and cp == prev + 1:
            prev = cp
            continue
        out.append(f"U+{start:X}" if start == prev else f"U+{start:X}-{prev:X}")
        if cp is not None:
            start = prev = cp
    return ", ".join(out)


def rename(font, family, weight):
    style = "Medium" if weight == 500 else "Regular"
    name = font["name"]
    for rec in list(name.names):
        if rec.nameID in (1, 4, 6, 16, 17, 21, 22):
            name.removeNames(nameID=rec.nameID)
    name.setName(family, 1, 3, 1, 0x409)
    name.setName("Regular", 2, 3, 1, 0x409)
    name.setName(f"{family} {style}", 4, 3, 1, 0x409)
    name.setName(f"{family.replace(' ', '')}-{style}", 6, 3, 1, 0x409)


def license_text(font):
    name = font["name"]
    parts = []
    for nid in (0, 13, 14):
        rec = name.getName(nid, 3, 1, 0x409) or name.getName(nid, 1, 0, 0)
        if rec:
            parts.append(rec.toUnicode())
    return "\n\n".join(parts)


def main():
    try:
        import brotli  # noqa: F401
        flavor, ext, fmt = "woff2", "woff2", "woff2"
    except ImportError:
        flavor, ext, fmt = "woff", "woff", "woff"
        print("brotli 没装，输出 WOFF（比 WOFF2 大一些）。pip install brotli 后重跑可以更小。")

    counts = corpus()
    order = [ch for ch, _ in counts.most_common()]
    for ch in ALWAYS:
        if ch not in counts:
            order.append(ch)
    always = set(ALWAYS)
    print(f"站点一共用到 {len(counts)} 个不同字符")

    rules = ["/* Generated by tools/build_fonts.py. Do not edit; run the script again instead. */"]
    built = 0
    for spec in FONTS:
        out_dir = OUT / spec["slug"]
        sources = {w: find_source(p) for w, p in spec["weights"].items()}
        if not any(sources.values()):
            print(f"跳过 {spec['source']}：tools/fonts-src/ 里没找到字体文件")
            continue
        if out_dir.exists():
            shutil.rmtree(out_dir)
        out_dir.mkdir(parents=True)
        for weight, src in sources.items():
            if not src:
                print(f"  {spec['source']} {weight}：没找到，跳过这个字重")
                continue
            base = TTFont(src, lazy=True)
            cmap = base.getBestCmap()
            notice = license_text(base)
            have = [ch for ch in order if ord(ch) in cmap]
            # First chunk: ASCII and punctuation plus the most frequent characters.
            first = [ch for ch in have if ch in always]
            rest = [ch for ch in have if ch not in always]
            chunks = [first + rest[:FIRST_CHUNK]]
            rest = rest[FIRST_CHUNK:]
            while rest:
                chunks.append(rest[:CHUNK])
                rest = rest[CHUNK:]
            total = 0
            for i, chars in enumerate(chunks):
                if not chars:
                    continue
                opts = subset.Options()
                opts.flavor = flavor
                opts.hinting = False
                opts.name_IDs = ["*"]
                opts.name_languages = ["*"]
                opts.notdef_outline = True
                opts.layout_features = ["*"]
                font = TTFont(src)
                sub = subset.Subsetter(opts)
                sub.populate(unicodes=[ord(c) for c in chars])
                sub.subset(font)
                rename(font, spec["family"], weight)
                tmp = out_dir / f"tmp.{ext}"
                font.flavor = flavor
                font.save(tmp)
                digest = hashlib.sha1(tmp.read_bytes()).hexdigest()[:8]
                fname = f"{weight}-{i}-{digest}.{ext}"
                tmp.rename(out_dir / fname)
                size = (out_dir / fname).stat().st_size
                total += size
                rules.append(
                    "@font-face {\n"
                    f'  font-family: "{spec["family"]}";\n'
                    f'  src: url("/fonts/{spec["slug"]}/{fname}") format("{fmt}");\n'
                    f"  font-weight: {weight};\n"
                    "  font-style: normal;\n"
                    "  font-display: swap;\n"
                    f"  unicode-range: {ranges([ord(c) for c in chars])};\n"
                    "}"
                )
            print(f"  {spec['source']} {weight}：{len(have)} 字，{len(chunks)} 块，共 {total / 1024:.0f} KB")
            built += 1
        (out_dir / "LICENSE.txt").write_text(
            f"{spec['family']} is a subset of {spec['source']}, made for this website.\n\n{notice}\n",
            encoding="utf-8",
        )

    CSS.write_text("\n".join(rules) + "\n", encoding="utf-8")
    print(f"写好了 {CSS.relative_to(ROOT)}" + ("" if built else "（没有任何字体，CSS 是空的）"))
    return 0 if built else 1


if __name__ == "__main__":
    sys.exit(main())
